#!/bin/bash
# t11: записує у файл $2 вміст усіх файлів за шаблоном $1, додаючи до кожного заголовок з його імʼям
if [ $# -ne 2 ]; then
    echo "Використання: $0 'шаблон' файл_результату"
    exit 1
fi
for f in $1; do
    [ -f "$f" ] || continue
    echo "Файл $f:"
    cat "$f"
done > "$2"
cat "$2"
