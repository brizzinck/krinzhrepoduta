#!/bin/bash
# t16: якщо в поточному каталозі є файли за маскою $1, записує в файл $2 назву й зміст кожного;
#      інакше записує повідомлення про відсутність файлів і дописує вміст каталогу
# маску слід передавати в лапках, щоб її розкрив не інтерпретатор у командному рядку, а цикл нижче
mask="$1"
out="$2"
found=0
: > "$out"
for f in $mask; do
    if [ -f "$f" ]; then
        echo "Файл $f:" >> "$out"
        cat "$f" >> "$out"
        found=1
    fi
done
if [ $found -eq 0 ]; then
    echo "Файлів за маскою '$mask' немає" >> "$out"
    ls >> "$out"
fi
cat "$out"
