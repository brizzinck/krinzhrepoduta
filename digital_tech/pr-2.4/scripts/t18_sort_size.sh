#!/bin/bash
# t18: перший параметр це файл; якщо його розмір більший за нуль, вміст сортується
# у зворотному порядку, зберігається у файл $2 і виводиться на екран
if [ $# -ne 2 ]; then
    echo "Використання: $0 файл результат"
    exit 1
fi
if [ -s "$1" ]; then
    sort -r "$1" > "$2"
    echo "Результат у файлі $2:"
    cat "$2"
else
    echo "Файл '$1' порожній або відсутній"
fi
