#!/bin/bash
# t07: обчислює обʼєм циліндра V = pi * r^2 * h
# expr працює лише з цілими числами, тому дробові обчислення виконує bc (a(1) = arctg(1) = pi/4)
echo -n "Радіус основи, см: "
read r
echo -n "Висота, см: "
read h
v=$(echo "scale=20; 4*a(1)*$r*$r*$h" | bc -l)
printf "Обʼєм циліндра: %.2f куб. см\n" "$v"
