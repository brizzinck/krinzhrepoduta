#!/bin/bash
# t15: якщо $1 є каталогом, який можна читати, показує його вміст;
#      якщо каталогу (файлу) немає, створює каталог; якщо це не каталог, показує вміст файлу
if [ -d "$1" ]; then
    if [ -r "$1" ]; then
        ls -l "$1"
    else
        echo "Каталог '$1' існує, але його не можна читати"
    fi
elif [ -e "$1" ]; then
    cat "$1"
else
    mkdir "$1"
    echo "Каталогу '$1' не було, його створено"
fi
