#!/bin/bash
# t17 (варіант б): імена файлів передаються позиційними параметрами $1 (джерело) і $2 (приймач)
if [ $# -ne 2 ]; then
    echo "Використання: $0 джерело приймач"
    exit 1
fi
if [ ! -e "$1" ] || [ ! -e "$2" ]; then
    echo "Відсутній файл: $1 або $2"
elif [ -r "$1" ] && [ -w "$2" ]; then
    cat "$1" > "$2"
    echo "Вміст $1 перенаправлено в $2"
else
    echo "Атрибути не збігаються: $1 має бути для читання, $2 для запису"
fi
