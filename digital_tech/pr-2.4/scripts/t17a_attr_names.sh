#!/bin/bash
# t17 (варіант а): імена файлів задано в самому скрипті.
# Якщо перший файл існує й читається, а другий існує й доступний для запису,
# вміст першого перенаправляється в другий; інакше виводиться повідомлення
src=cars_a.txt
dst=copy.out
if [ ! -e "$src" ] || [ ! -e "$dst" ]; then
    echo "Відсутній файл: $src або $dst"
elif [ -r "$src" ] && [ -w "$dst" ]; then
    cat "$src" > "$dst"
    echo "Вміст $src перенаправлено в $dst"
else
    echo "Атрибути не збігаються: $src має бути для читання, $dst для запису"
fi
